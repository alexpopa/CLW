/** Deterministic PRNG (mulberry32). NEVER use Math.random() inside the sim. */
export class Rng {
  constructor(private s: number) { this.s >>>= 0; }
  next(): number {
    this.s = (this.s + 0x6d2b79f5) >>> 0;
    let t = this.s;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  }
  int(maxExclusive: number): number { return Math.floor(this.next() * maxExclusive); }
  get state(): number { return this.s; }
}
